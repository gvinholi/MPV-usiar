"""Generate Zod/TypeScript HTTP contracts from the existing Python AST, without importing the API.

Run from any directory with Python 3.13+: python frontend/scripts/generate-contracts.py [--check]
No collector changes, dependencies, database, or running server required.
"""
import ast
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[2]
schema_paths = [
    ROOT / "collector/src/collector/api/schemas.py",
    ROOT / "collector/src/collector/api/auth_schemas.py",
]
schema_modules = [ast.parse(path.read_text(encoding="utf-8")) for path in schema_paths]
models = ast.parse((ROOT / "collector/src/collector/application/human_review/models.py").read_text(encoding="utf-8"))
schema_classes = {
    node.name: node
    for module in schema_modules
    for node in module.body
    if isinstance(node, ast.ClassDef)
}
lines = ['// Generated by scripts/generate-contracts.py from FastAPI HTTP schemas. Do not edit.',
         'import { z } from "zod";', '']
for node in models.body:
    if isinstance(node, ast.ClassDef) and any(isinstance(base, ast.Name) and base.id == "StrEnum" for base in node.bases):
        values = [repr(item.value.value).replace("'", '"') for item in node.body if isinstance(item, ast.Assign)]
        lines.append(f'export const {node.name}Schema = z.enum([{", ".join(values)}]);')


def class_extra_policy(name, seen=None):
    """Resolve Pydantic extra policy through local model inheritance."""
    seen = set() if seen is None else seen
    if name in seen:
        raise ValueError(f"cyclic schema inheritance: {name}")
    seen.add(name)
    node = schema_classes[name]
    for statement in node.body:
        if not isinstance(statement, ast.Assign):
            continue
        if not any(isinstance(target, ast.Name) and target.id == "model_config" for target in statement.targets):
            continue
        if isinstance(statement.value, ast.Call) and isinstance(statement.value.func, ast.Name) and statement.value.func.id == "ConfigDict":
            for keyword in statement.value.keywords:
                if keyword.arg == "extra" and isinstance(keyword.value, ast.Constant):
                    return keyword.value.value
    for base in node.bases:
        if isinstance(base, ast.Name) and base.id in schema_classes:
            inherited = class_extra_policy(base.id, seen)
            if inherited is not None:
                return inherited
    return None


def nullable_annotation(node):
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.BitOr):
        if isinstance(node.left, ast.Constant) and node.left.value is None:
            return node.right
        if isinstance(node.right, ast.Constant) and node.right.value is None:
            return node.left
    return None


def expression(node, constraints=None):
    constraints = constraints or {}
    nullable = nullable_annotation(node)
    if nullable is not None:
        return expression(nullable, constraints) + ".nullable()"
    if isinstance(node, ast.Name):
        value = {"str": "z.string()", "StrictStr": "z.string()", "int": "z.number().int()", "bool": "z.boolean()",
                 "UUID": "z.uuid()", "datetime": "z.iso.datetime({ offset: true })"}.get(node.id, node.id + "Schema")
        if node.id == "StrictStr" and constraints:
            checks = []
            if "min_length" in constraints:
                checks.append(f"length >= {constraints['min_length']}")
            if "max_length" in constraints:
                checks.append(f"length <= {constraints['max_length']}")
            value += ".refine(value => { const length = Array.from(value).length; return " + " && ".join(checks) + "; })"
        elif node.id == "str":
            if "min_length" in constraints:
                value += f'.min({constraints["min_length"]})'
            if "max_length" in constraints:
                value += f'.max({constraints["max_length"]})'
        return value
    if isinstance(node, ast.Subscript) and isinstance(node.value, ast.Name) and node.value.id == "list":
        return "z.array(" + expression(node.slice) + ")"
    raise ValueError(ast.dump(node))


def field_metadata(field):
    """Return whether a default exists, its value, and supported Field constraints."""
    if field.value is None:
        return False, None, {}
    value = field.value
    constraints = {}
    if isinstance(value, ast.Call) and isinstance(value.func, ast.Name) and value.func.id == "Field":
        default_node = value.args[0] if value.args else None
        for keyword in value.keywords:
            if keyword.arg == "default":
                default_node = keyword.value
            elif keyword.arg in {"min_length", "max_length"}:
                constraints[keyword.arg] = ast.literal_eval(keyword.value)
        if default_node is None:
            return False, None, constraints
        return True, ast.literal_eval(default_node), constraints
    return True, ast.literal_eval(value), constraints


for node in (node for module in schema_modules for node in module.body):
    if not isinstance(node, ast.ClassDef) or node.name in {"HttpModel", "PageResponse"}:
        continue
    lines.append(f"export const {node.name}Schema = z.object({{")
    for field in node.body:
        if isinstance(field, ast.AnnAssign):
            has_default, default, constraints = field_metadata(field)
            value = expression(field.annotation, constraints)
            if has_default:
                value += f".default({json.dumps(default)})"
            lines.append(f"  {field.target.id}: {value},")
    suffix = "}).strict();" if class_extra_policy(node.name) == "forbid" else "});"
    lines.extend([suffix, f"export type {node.name} = z.infer<typeof {node.name}Schema>;", ""])
lines.extend(['export const pageSchema = <T extends z.ZodType>(item: T) => z.object({',
              '  items: z.array(item), pagination: PaginationResponseSchema,',
              '}).strict();' if class_extra_policy("PageResponse") == "forbid" else '});',
              'export type PageResponse<T> = { items: T[]; pagination: PaginationResponse };', ''])
content = "\n".join(lines)
target = ROOT / "frontend/src/lib/server/api/contracts.generated.ts"
if "--check" in sys.argv:
    if not target.exists() or target.read_text(encoding="utf-8") != content:
        sys.exit("HTTP contracts are out of date")
else:
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding="utf-8")
